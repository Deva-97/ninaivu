import 'package:ninaivu/domain/entities/client.dart';

class ClientModel extends Client {
  const ClientModel({
    required super.id,
    required super.businessId,
    required super.name,
    required super.mobile,
    super.alternateMobile,
    super.email,
    super.address,
    super.areaCity,
    super.notes,
    super.profileImagePath,
    super.dateOfBirthMs,
    super.specialDateMs,
    super.specialDateLabel,
    required super.createdBy,
    super.agentId,
    super.subAgentId,
    super.customerUserId,
    super.assignedTo,
    required super.createdAt,
    required super.updatedAt,
    required super.isDeleted,
    required super.syncStatus,
    super.policyCount,
  });

  factory ClientModel.fromEntity(Client entity) {
    return ClientModel(
      id: entity.id,
      businessId: entity.businessId,
      name: entity.name,
      mobile: entity.mobile,
      alternateMobile: entity.alternateMobile,
      email: entity.email,
      address: entity.address,
      areaCity: entity.areaCity,
      notes: entity.notes,
      profileImagePath: entity.profileImagePath,
      dateOfBirthMs: entity.dateOfBirthMs,
      specialDateMs: entity.specialDateMs,
      specialDateLabel: entity.specialDateLabel,
      createdBy: entity.createdBy,
      agentId: entity.agentId,
      subAgentId: entity.subAgentId,
      customerUserId: entity.customerUserId,
      assignedTo: entity.assignedTo,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
      isDeleted: entity.isDeleted,
      syncStatus: entity.syncStatus,
      policyCount: entity.policyCount,
    );
  }

  ClientModel copyWith({
    String? id,
    String? businessId,
    String? name,
    String? mobile,
    String? alternateMobile,
    String? email,
    String? address,
    String? areaCity,
    String? notes,
    String? profileImagePath,
    int? dateOfBirthMs,
    int? specialDateMs,
    String? specialDateLabel,
    String? createdBy,
    String? agentId,
    String? subAgentId,
    String? customerUserId,
    String? assignedTo,
    int? createdAt,
    int? updatedAt,
    bool? isDeleted,
    String? syncStatus,
    int? policyCount,
  }) {
    return ClientModel(
      id: id ?? this.id,
      businessId: businessId ?? this.businessId,
      name: name ?? this.name,
      mobile: mobile ?? this.mobile,
      alternateMobile: alternateMobile ?? this.alternateMobile,
      email: email ?? this.email,
      address: address ?? this.address,
      areaCity: areaCity ?? this.areaCity,
      notes: notes ?? this.notes,
      profileImagePath: profileImagePath ?? this.profileImagePath,
      dateOfBirthMs: dateOfBirthMs ?? this.dateOfBirthMs,
      specialDateMs: specialDateMs ?? this.specialDateMs,
      specialDateLabel: specialDateLabel ?? this.specialDateLabel,
      createdBy: createdBy ?? this.createdBy,
      agentId: agentId ?? this.agentId,
      subAgentId: subAgentId ?? this.subAgentId,
      customerUserId: customerUserId ?? this.customerUserId,
      assignedTo: assignedTo ?? this.assignedTo,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      isDeleted: isDeleted ?? this.isDeleted,
      syncStatus: syncStatus ?? this.syncStatus,
      policyCount: policyCount ?? this.policyCount,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'business_id': businessId,
      'name': name,
      'mobile': mobile,
      'alternate_mobile': alternateMobile,
      'email': email,
      'address': address,
      'area_city': areaCity,
      'notes': notes,
      'profile_image_path': profileImagePath,
      'date_of_birth_ms': dateOfBirthMs,
      'special_date_ms': specialDateMs,
      'special_date_label': specialDateLabel,
      'created_by': createdBy,
      'agent_id': agentId,
      'sub_agent_id': subAgentId,
      'customer_user_id': customerUserId,
      'assigned_to': assignedTo,
      'created_at': createdAt,
      'updated_at': updatedAt,
      'is_deleted': isDeleted ? 1 : 0,
      'sync_status': syncStatus,
    };
  }

  factory ClientModel.fromMap(Map<String, dynamic> map) {
    return ClientModel(
      id: map['id'] as String,
      businessId: map['business_id'] as String,
      name: map['name'] as String,
      mobile: map['mobile'] as String,
      alternateMobile: map['alternate_mobile'] as String?,
      email: map['email'] as String?,
      address: map['address'] as String?,
      areaCity: map['area_city'] as String?,
      notes: map['notes'] as String?,
      profileImagePath: map['profile_image_path'] as String?,
      dateOfBirthMs: map['date_of_birth_ms'] as int?,
      specialDateMs: map['special_date_ms'] as int?,
      specialDateLabel: map['special_date_label'] as String?,
      createdBy: map['created_by'] as String,
      agentId: map['agent_id'] as String?,
      subAgentId: map['sub_agent_id'] as String?,
      customerUserId: map['customer_user_id'] as String?,
      assignedTo: map['assigned_to'] as String?,
      createdAt: map['created_at'] as int,
      updatedAt: map['updated_at'] as int,
      isDeleted: (map['is_deleted'] as int? ?? 0) == 1,
      syncStatus: map['sync_status'] as String? ?? 'synced',
      policyCount: map['policy_count'] as int? ?? 0,
    );
  }

  Map<String, dynamic> toFirestore() {
    return {
      'id': id,
      'businessId': businessId,
      'name': name,
      'mobile': mobile,
      'alternateMobile': alternateMobile,
      'email': email,
      'address': address,
      'areaCity': areaCity,
      'notes': notes,
      'profileImagePath': profileImagePath,
      'dateOfBirthMs': dateOfBirthMs,
      'specialDateMs': specialDateMs,
      'specialDateLabel': specialDateLabel,
      'createdBy': createdBy,
      'agentId': agentId,
      'subAgentId': subAgentId,
      'customerUserId': customerUserId,
      'assignedTo': assignedTo,
      'createdAt': createdAt,
      'updatedAt': updatedAt,
      'isDeleted': isDeleted,
      'syncStatus': syncStatus,
    };
  }

  factory ClientModel.fromFirestore(Map<String, dynamic> map) {
    return ClientModel(
      id: map['id'] as String,
      businessId: map['businessId'] as String,
      name: map['name'] as String,
      mobile: map['mobile'] as String,
      alternateMobile: map['alternateMobile'] as String?,
      email: map['email'] as String?,
      address: map['address'] as String?,
      areaCity: map['areaCity'] as String?,
      notes: map['notes'] as String?,
      profileImagePath: map['profileImagePath'] as String?,
      dateOfBirthMs: map['dateOfBirthMs'] as int?,
      specialDateMs: map['specialDateMs'] as int?,
      specialDateLabel: map['specialDateLabel'] as String?,
      createdBy: map['createdBy'] as String,
      agentId: map['agentId'] as String?,
      subAgentId: map['subAgentId'] as String?,
      customerUserId: map['customerUserId'] as String?,
      assignedTo: map['assignedTo'] as String?,
      createdAt: map['createdAt'] as int,
      updatedAt: map['updatedAt'] as int,
      isDeleted: map['isDeleted'] as bool? ?? false,
      syncStatus: map['syncStatus'] as String? ?? 'synced',
      policyCount: map['policyCount'] as int? ?? 0,
    );
  }
}
