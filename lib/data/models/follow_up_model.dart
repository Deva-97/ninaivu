import 'package:ninaivu/domain/entities/follow_up.dart';

class FollowUpModel extends FollowUp {
  const FollowUpModel({
    required super.id,
    required super.businessId,
    required super.clientId,
    super.policyId,
    required super.followUpDateTime,
    required super.type,
    required super.status,
    super.remarks,
    required super.createdBy,
    super.agentId,
    super.subAgentId,
    super.customerUserId,
    super.assignedTo,
    required super.createdAt,
    required super.updatedAt,
    required super.isDeleted,
    required super.syncStatus,
    super.clientName,
    super.clientMobile,
    super.policyNumber,
  });

  factory FollowUpModel.fromEntity(FollowUp entity) {
    return FollowUpModel(
      id: entity.id,
      businessId: entity.businessId,
      clientId: entity.clientId,
      policyId: entity.policyId,
      followUpDateTime: entity.followUpDateTime,
      type: entity.type,
      status: entity.status,
      remarks: entity.remarks,
      createdBy: entity.createdBy,
      agentId: entity.agentId,
      subAgentId: entity.subAgentId,
      customerUserId: entity.customerUserId,
      assignedTo: entity.assignedTo,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
      isDeleted: entity.isDeleted,
      syncStatus: entity.syncStatus,
      clientName: entity.clientName,
      clientMobile: entity.clientMobile,
      policyNumber: entity.policyNumber,
    );
  }

  FollowUpModel copyWith({
    String? id,
    String? businessId,
    String? clientId,
    String? policyId,
    bool clearPolicyId = false,
    int? followUpDateTime,
    String? type,
    String? status,
    String? remarks,
    bool clearRemarks = false,
    String? createdBy,
    String? agentId,
    String? subAgentId,
    String? customerUserId,
    String? assignedTo,
    int? createdAt,
    int? updatedAt,
    bool? isDeleted,
    String? syncStatus,
    String? clientName,
    String? clientMobile,
    String? policyNumber,
  }) {
    return FollowUpModel(
      id: id ?? this.id,
      businessId: businessId ?? this.businessId,
      clientId: clientId ?? this.clientId,
      policyId: clearPolicyId ? null : policyId ?? this.policyId,
      followUpDateTime: followUpDateTime ?? this.followUpDateTime,
      type: type ?? this.type,
      status: status ?? this.status,
      remarks: clearRemarks ? null : remarks ?? this.remarks,
      createdBy: createdBy ?? this.createdBy,
      agentId: agentId ?? this.agentId,
      subAgentId: subAgentId ?? this.subAgentId,
      customerUserId: customerUserId ?? this.customerUserId,
      assignedTo: assignedTo ?? this.assignedTo,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      isDeleted: isDeleted ?? this.isDeleted,
      syncStatus: syncStatus ?? this.syncStatus,
      clientName: clientName ?? this.clientName,
      clientMobile: clientMobile ?? this.clientMobile,
      policyNumber: policyNumber ?? this.policyNumber,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'business_id': businessId,
      'client_id': clientId,
      'policy_id': policyId,
      'follow_up_date_time': followUpDateTime,
      'type': type,
      'status': status,
      'remarks': remarks,
      'created_by': createdBy,
      'agent_id': agentId,
      'sub_agent_id': subAgentId,
      'customer_user_id': customerUserId,
      'assigned_to': assignedTo,
      'created_at': createdAt,
      'updated_at': updatedAt,
      'is_deleted': isDeleted ? 1 : 0,
      'sync_status': syncStatus,
    };
  }

  factory FollowUpModel.fromMap(Map<String, dynamic> map) {
    return FollowUpModel(
      id: map['id'] as String,
      businessId: map['business_id'] as String,
      clientId: map['client_id'] as String,
      policyId: map['policy_id'] as String?,
      followUpDateTime: map['follow_up_date_time'] as int,
      type: map['type'] as String,
      status: map['status'] as String,
      remarks: map['remarks'] as String?,
      createdBy: map['created_by'] as String,
      agentId: map['agent_id'] as String?,
      subAgentId: map['sub_agent_id'] as String?,
      customerUserId: map['customer_user_id'] as String?,
      assignedTo: map['assigned_to'] as String?,
      createdAt: map['created_at'] as int,
      updatedAt: map['updated_at'] as int,
      isDeleted: (map['is_deleted'] as int? ?? 0) == 1,
      syncStatus: map['sync_status'] as String? ?? 'synced',
      clientName: map['client_name'] as String?,
      clientMobile: map['client_mobile'] as String?,
      policyNumber: map['policy_number'] as String?,
    );
  }

  Map<String, dynamic> toFirestore() {
    return {
      'id': id,
      'businessId': businessId,
      'clientId': clientId,
      'policyId': policyId,
      'followUpDateTime': followUpDateTime,
      'type': type,
      'status': status,
      'remarks': remarks,
      'createdBy': createdBy,
      'agentId': agentId,
      'subAgentId': subAgentId,
      'customerUserId': customerUserId,
      'assignedTo': assignedTo,
      'createdAt': createdAt,
      'updatedAt': updatedAt,
      'isDeleted': isDeleted,
      'syncStatus': syncStatus,
      'clientName': clientName,
      'clientMobile': clientMobile,
      'policyNumber': policyNumber,
    };
  }

  factory FollowUpModel.fromFirestore(Map<String, dynamic> map) {
    return FollowUpModel(
      id: map['id'] as String,
      businessId: map['businessId'] as String,
      clientId: map['clientId'] as String,
      policyId: map['policyId'] as String?,
      followUpDateTime: map['followUpDateTime'] as int,
      type: map['type'] as String,
      status: map['status'] as String,
      remarks: map['remarks'] as String?,
      createdBy: map['createdBy'] as String,
      agentId: map['agentId'] as String?,
      subAgentId: map['subAgentId'] as String?,
      customerUserId: map['customerUserId'] as String?,
      assignedTo: map['assignedTo'] as String?,
      createdAt: map['createdAt'] as int,
      updatedAt: map['updatedAt'] as int,
      isDeleted: map['isDeleted'] as bool? ?? false,
      syncStatus: map['syncStatus'] as String? ?? 'synced',
      clientName: map['clientName'] as String?,
      clientMobile: map['clientMobile'] as String?,
      policyNumber: map['policyNumber'] as String?,
    );
  }
}
